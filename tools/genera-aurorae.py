#!/usr/bin/env python3
"""
genera-aurorae.py — Builds the Meridiano window decoration (Aurorae).

Why a generator and not hand-written SVGs
─────────────────────────────────────────
An Aurorae theme is an 84x84 sprite split into nine regions on a fixed
17 / 67 / 84 grid, and every edge has to meet the neighbouring region
to the pixel. Written by hand, two edges that touch always end up half
a pixel apart: the window gets a light or dark line at one corner, and
it shows.

Here the geometry is computed, so the edges match by construction.

The grid (from the Cyber-Blue reference theme):
    topleft  0,0 17x17        top    17,0  50x17   (repeated horizontally)
    left    0,17 17x50        center 17,17 50x50   (repeated in both)
    right  67,17 17x50
    bottomleft 0,67 17x17     bottom 17,67 50x17   (repeated horizontally)
    topright  67,0 17x17      bottomright 67,67 17x17

Usage:
    python3 tools/genera-aurorae.py [--out DIR]
"""

from __future__ import annotations

import argparse
from pathlib import Path

# ── Palette, identical to src/theme/color-schemes/Meridiano.colors ────────
SURFACE_H = "#22201d"   # raised surface: the title bar
FIELD_L   = "#16140f"   # lightened background: the window body
RULE      = "#2a2825"   # structural border
AMBER     = "#ff9d2e"   # accent

SVG_HEAD = '''<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     width="84" height="84" viewBox="0 0 84 84" version="1.1">
<!--
  Meridiano — window decoration
  Generated by tools/genera-aurorae.py. Do not edit by hand: the edges
  of the nine regions have to match to the pixel.
-->
<defs>
  <clipPath id="clip-tl"><rect x="0"  y="0"  width="17" height="17"/></clipPath>
  <clipPath id="clip-t"><rect x="17"  y="0"  width="50" height="17"/></clipPath>
  <clipPath id="clip-tr"><rect x="67"  y="0"  width="17" height="17"/></clipPath>
  <clipPath id="clip-l"><rect x="0"  y="17" width="17" height="50"/></clipPath>
  <clipPath id="clip-c"><rect x="17"  y="17" width="50" height="50"/></clipPath>
  <clipPath id="clip-r"><rect x="67"  y="17" width="17" height="50"/></clipPath>
  <clipPath id="clip-bl"><rect x="0"  y="67" width="17" height="17"/></clipPath>
  <clipPath id="clip-b"><rect x="17"  y="67" width="50" height="17"/></clipPath>
  <clipPath id="clip-br"><rect x="67"  y="67" width="17" height="17"/></clipPath>
</defs>
'''


def regione(id_, clip, corpo, extra=""):
    return f'<g id="{id_}"{extra} clip-path="url(#{clip})">\n{corpo}\n</g>'






def decora(sfondo_corpo, titolo, accento):
    """The nine regions of the decoration.

    Nine groups, nine unique `id`s. No more: see the note in main().
    """
    r = []

    # ── Top corners: the title strip reaches the edge ──
    #
    # Each of the three top regions carries the separator on its own
    # bottom edge. All three have to carry it: the middle region
    # stretches horizontally, the corner ones stay 1:1, and if the
    # separator is only in the middle you get a dash at the centre of the
    # window with two fragments at the sides — which is exactly the look
    # I did not want, and which I had produced before by putting it on
    # the sides.
    r.append(regione("decoration-topleft", "clip-tl", "\n".join([
        f'<rect x="0" y="0" width="17" height="17" fill="{titolo}"/>',
        f'<rect x="0" y="0" width="17" height="1" fill="{RULE}"/>',
        f'<rect x="0" y="0" width="1" height="17" fill="{RULE}"/>',
        # The amber notch: an active window is recognised by this.
        f'<rect x="1" y="0" width="16" height="1" fill="{accento}"/>',
        f'<rect x="0" y="16" width="17" height="1" fill="{RULE}"/>',
    ])))

    r.append(regione("decoration-top", "clip-t", "\n".join([
        f'<rect x="17" y="0" width="50" height="17" fill="{titolo}"/>',
        f'<rect x="17" y="0" width="50" height="1" fill="{RULE}"/>',
        f'<rect x="17" y="0" width="50" height="1" fill="{accento}"/>',
        f'<rect x="17" y="16" width="50" height="1" fill="{RULE}"/>',
    ])))

    r.append(regione("decoration-topright", "clip-tr", "\n".join([
        f'<rect x="67" y="0" width="17" height="17" fill="{titolo}"/>',
        f'<rect x="67" y="0" width="17" height="1" fill="{RULE}"/>',
        f'<rect x="83" y="0" width="1" height="17" fill="{RULE}"/>',
        f'<rect x="67" y="0" width="16" height="1" fill="{accento}"/>',
        f'<rect x="67" y="16" width="17" height="1" fill="{RULE}"/>',
    ])))

    # ── Sides: outer border, body just darker than the bar ──
    #
    # No horizontal rules here. The side regions of the nine-slice are
    # stretched vertically up to the window height, and a horizontal
    # rule inside one of them does not stretch: it repeats, or a 16px
    # dash is left hanging off the edge. That is what was visible: two
    # 16px fragments below the title bar, at the two sides, with the
    # middle clean. It looked like a rule that had been erased.
    #
    # The separator under the title is drawn by the top region, which
    # stretches only horizontally: there a horizontal rule is exactly
    # what it should be, and it comes out continuous from corner to
    # corner.
    r.append(regione("decoration-left", "clip-l", "\n".join([
        f'<rect x="0" y="17" width="17" height="50" fill="{sfondo_corpo}"/>',
        f'<rect x="0" y="17" width="1" height="50" fill="{RULE}"/>',
    ])))

    r.append(regione("decoration-center", "clip-c", "\n".join([
        f'<rect x="17" y="17" width="50" height="50" fill="{sfondo_corpo}"/>',
    ])))

    r.append(regione("decoration-right", "clip-r", "\n".join([
        f'<rect x="67" y="17" width="17" height="50" fill="{sfondo_corpo}"/>',
        f'<rect x="83" y="17" width="1" height="50" fill="{RULE}"/>',
    ])))

    # ── Bottom corners ──
    r.append(regione("decoration-bottomleft", "clip-bl", "\n".join([
        f'<rect x="0" y="67" width="17" height="17" fill="{sfondo_corpo}"/>',
        f'<rect x="0" y="83" width="17" height="1" fill="{RULE}"/>',
        f'<rect x="0" y="67" width="1" height="16" fill="{RULE}"/>',
    ])))

    r.append(regione("decoration-bottom", "clip-b", "\n".join([
        f'<rect x="17" y="67" width="50" height="17" fill="{sfondo_corpo}"/>',
        f'<rect x="17" y="83" width="50" height="1" fill="{RULE}"/>',
    ])))

    r.append(regione("decoration-bottomright", "clip-br", "\n".join([
        f'<rect x="67" y="67" width="17" height="17" fill="{sfondo_corpo}"/>',
        f'<rect x="67" y="83" width="17" height="1" fill="{RULE}"/>',
        f'<rect x="83" y="67" width="1" height="16" fill="{RULE}"/>',
    ])))

    return "\n".join(r)


# The four states of a button, and the colour of each.
#
# `active` is the resting state of a foreground window: dim text, not
# full. A full-contrast button on a dark bar is the first thing the eye
# goes to read, and the foreground should be the title. The glyph lights
# up only when you use it.
#
#   active    resting, foreground window     dim text
#   hover     the pointer is over it          full text
#   pressed   held down                      amber
#   inactive  window not in the foreground   even dimmer
STATI = {
    "active":   "#8a857c",
    "hover":    "#e8e4dc",
    "pressed":  "#ff9d2e",
    "inactive": "#565248",
}


def pulsante(corpixml: str, nome: str, description: str) -> str:
    """An 18x18 button, filled glyphs, one per state.

    ── Why a <g id="state-center"> for every state ─────────────────────────
    The file has to declare its states with the id. Without them Aurorae
    draws nothing: no error, no warning, the button's space is simply
    reserved and empty. With `close.svg` reduced to two loose paths the
    title bar had the right space and the void.

    Measured: 210 "non-background" pixels without the ids, 348 with. The
    group name is `{state}-center`, not `active` and not `normal`.

    ── Why filled shapes and not strokes ───────────────────────────────────
    The first version used 1.2px strokes with `fill="none"`: at 18px,
    scaled by Aurorae onto non-integer pixels, they antialias almost
    away. Filled shapes are robust at any scale and, for a theme that
    wants its symbols as references rather than illustrations, they are
    also more correct: a filled X is a glyph, a dashed X is a drawing.
    """
    livelli = []
    for stato, colore in STATI.items():
        livelli.append(
            f'<g id="{stato}-center">\n{corpixml.replace("COLOR", colore)}\n</g>')
    return f'''<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 18 18">
<!-- {nome}: {description}. One <g> per state: Aurorae reads the ids. -->
{chr(10).join(livelli)}
</svg>
'''


def pulsanti() -> dict[str, str]:
    """The button glyphs, one per state.

    ── The rule about the ends ─────────────────────────────────────────────
    No rounded ends. On a bar 1.4px high an `rx` of 0.7 turns it into a
    capsule: at 18px the two ends merge into the body and the glyph reads
    as a dot rather than a bar. The application menu looked like a list
    of debris because it was made of three 1.4px capsules, not because
    the icon was wrong.

    ── The rule about fill and outline ─────────────────────────────────────
    A filled symbol only reads if it is small and unambiguous. A filled
    square does not say "maximise": it says "block". The square has to
    be drawn as a frame, with a thickness that survives antialiasing:
    1.5px at 18px holds, 1.2px does not — which is why the first version
    used filled shapes, and why the outlines are now thicker than they
    were then rather than the same 1.2px.
    """
    p: dict[str, str] = {}

    # ── Close: filled X ────────────────────────────────────────────────────
    # It stays filled. An X is already diagonal: rounded ends would only
    # add thickness where none is needed, and the two strokes would cut
    # into each other.
    L, w = 4.6, 0.9
    br = []
    for sx in (-1, 1):
        for sy in (-1, 1):
            dx, dy = sx / 2 ** 0.5, sy / 2 ** 0.5
            qx, qy = sy / 2 ** 0.5, -sx / 2 ** 0.5
            cx, cy = 9.0, 9.0
            tx, ty = cx + dx * L, cy + dy * L
            punti = [(cx + qx * w, cy + qy * w), (tx + qx * w, ty + qy * w),
                     (tx - qx * w, ty - qy * w), (cx - qx * w, cy - qy * w)]
            d = "M " + " L ".join(f"{x:.3f},{y:.3f}" for x, y in punti) + " Z"
            br.append(f'<path fill="COLOR" d="{d}"/>')
    p["close"] = pulsante("\n  ".join(br), "Close", "a filled X")

    # ── Maximise: a frame ──────────────────────────────────────────────────
    p["maximize"] = pulsante(
        '<rect x="4.75" y="4.75" width="8.5" height="8.5" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>',
        "Maximise", "a frame")

    # ── Restore: two offset frames ─────────────────────────────────────────
    p["restore"] = pulsante(
        '<rect x="7.25" y="4.75" width="6" height="6" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>\n'
        '  <rect x="4.75" y="7.25" width="6" height="6" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>',
        "Restore", "two offset frames")

    # ── Minimise: a bar ────────────────────────────────────────────────────
    p["minimize"] = pulsante(
        '<rect x="4.5" y="8.25" width="9" height="1.5" fill="COLOR"/>',
        "Minimise", "a bar")

    # ── Shade: two bars ────────────────────────────────────────────────────
    p["shade"] = pulsante(
        '<rect x="4.5" y="6.25" width="6" height="1.5" fill="COLOR"/>\n'
        '  <rect x="4.5" y="10.25" width="9" height="1.5" fill="COLOR"/>',
        "Shade", "two bars")

    # ── Menu: three bars ───────────────────────────────────────────────────
    # 3px spacing and 1.5px height: the gap between one bar and the next
    # is larger than the bar itself, otherwise they merge into a block
    # and the menu looks like a rectangle.
    p["menu"] = pulsante(
        '<rect x="4.5" y="5.25" width="9" height="1.5" fill="COLOR"/>\n'
        '  <rect x="4.5" y="8.25" width="9" height="1.5" fill="COLOR"/>\n'
        '  <rect x="4.5" y="11.25" width="9" height="1.5" fill="COLOR"/>',
        "Menu", "three bars")

    # ── On all desktops: two monitors side by side ─────────────────────────
    # Not two offset frames like `restore`: they were
    # indistinguishable, and two different buttons that read the same
    # are two buttons nobody understands. Side by side they read as
    # "two screens", which is what the button means.
    p["alldesktops"] = pulsante(
        # The gap between the two frames has to exceed the stroke
        # thickness, otherwise the two edges touch and the icon reads as
        # a filled rectangle. With 1.5px strokes you need at least 3px
        # of air.
        #
        # This comment has been describing that fix for a while without
        # it being in the numbers: the frames were 1.5px apart, which is
        # exactly the value the comment says makes the button a block,
        # and that is why it rendered as a solid square. Recomputed
        # here rather than nudged: two 5px frames plus two 1.5px strokes
        # plus 3px of air is 16px, which leaves 1px of margin on each
        # side of an 18px button.
        '<rect x="1.75" y="5.75" width="5" height="6.5" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>\n'
        '  <rect x="11.25" y="5.75" width="5" height="6.5" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>',
        "On all desktops", "two monitors side by side")

    # ── Keep above: a frame with a dash ────────────────────────────────────
    p["keepabove"] = pulsante(
        '<rect x="4.75" y="4.75" width="8.5" height="8.5" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>\n'
        '  <rect x="4.75" y="7.25" width="8.5" height="1.5" fill="COLOR"/>',
        "Keep above", "a frame with a dash")

    p["keepbelow"] = pulsante(
        '<rect x="4.75" y="4.75" width="8.5" height="8.5" fill="none" '
        'stroke="COLOR" stroke-width="1.5"/>\n'
        '  <rect x="4.75" y="7.25" width="8.5" height="1.5" fill="COLOR"/>',
        "Keep below", "a frame with a dash")

    return p


