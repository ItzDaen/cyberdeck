def _verifica(svg: str, nome: str) -> None:
    """Never let an SVG out with duplicate `id`s.

    A repeated `id` is not a detail: it is an invalid file, and which of
    the two definitions wins depends on the renderer. The symptom that
    follows is the worst possible — a decoration that looks working with
    half its elements missing — and it leaves no error in the console.
    Better to fail here, with a message that says what is duplicated.
    """
    import re
    ids = re.findall(r'\bid="([^"]+)"', svg)
    duplicati = sorted({i for i in ids if ids.count(i) > 1})
    if duplicati:
        raise SystemExit(
            f"  ✗ {nome}: duplicate ids: {', '.join(duplicati)}\n"
            f"    Each region must appear exactly once."
        )


def _non_vuoto(svg: str, nome: str) -> None:
    """Never let out a glyph that draws nothing.

    The static check passed: the X's four `<path>` elements were there,
    they had a `fill`, and the file was valid XML. But each one's three
    points lay on the same line, so the area was zero and the glyph
    rendered nothing. Three hours of trials on real windows to find a
    degenerate triangle.

    Rasterising and comparing against the same empty SVG is the only
    check that distinguishes "the file is there" from "the file draws
    something".

    The comparison is on the PNG's bytes, and only at equal dimensions:
    the first version compared a 72px render with an 18px one and
    detected nothing, because two PNGs of different sizes are never
    identical even when both are empty.
    """
    import subprocess
    import tempfile

    VUOTO = ('<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" '
             'viewBox="0 0 18 18"></svg>')
    with tempfile.TemporaryDirectory() as td:
        src = Path(td) / "g.svg"
        vuoto = Path(td) / "v.png"
        pieno = Path(td) / "p.png"
        src.write_text(svg, encoding="utf-8")
        for testo, out in ((svg, pieno), (VUOTO, vuoto)):
            src.write_text(testo, encoding="utf-8")
            try:
                subprocess.run(
                    ["rsvg-convert", "-w", "72", "-h", "72", "-b", "#ff00ff",
                     str(src), "-o", str(out)],
                    check=True, capture_output=True, timeout=20)
            except (FileNotFoundError, subprocess.CalledProcessError,
                    subprocess.TimeoutExpired):
                return          # without rsvg there is nothing to check
        if vuoto.read_bytes() == pieno.read_bytes():
            raise SystemExit(
                f"  ✗ {nome}: the glyph draws nothing (identical to an "
                f"empty SVG). Degenerate paths or wrong coordinates."
            )



def main() -> None:
    ap = argparse.ArgumentParser(description="Builds the Meridiano Aurorae theme")
    ap.add_argument("--out", required=True, help="destination directory")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    # The nine regions, once.
    #
    # I had emitted two sets: one for the active window and one for the
    # inactive one, with `opacity="0.0"` on the second. The underlying
    # assumption — that two copies are needed to tell the states apart —
    # is false: `decoration.svg` holds a single set of nine regions, and
    # it is Aurorae that handles active and inactive. Two copies with
    # the same `id` are an invalid SVG, and the renderer takes the last
    # one: the title bar disappeared entirely and only the text was
    # left, which comes from the colour scheme and not from the SVG. A
    # file that cancels itself out is the worst kind of defect, because
    # it looks like it works.
    svg = SVG_HEAD + decora(FIELD_L, SURFACE_H, AMBER) + "\n</svg>\n"
    _verifica(svg, "decoration.svg")
    (out / "decoration.svg").write_text(svg, encoding="utf-8")

    for nome, contenuto in pulsanti().items():
        (out / f"{nome}.svg").write_text(contenuto, encoding="utf-8")
        _non_vuoto(contenuto, f"{nome}.svg")

    (out / "Meridianorc").write_text(RC, encoding="utf-8")
    (out / "metadata.desktop").write_text(METADATA, encoding="utf-8")

    generated_files = sorted(p.name for p in out.iterdir())
    print(f"  ✓ {out}")
    print(f"  ✓ {len(generated_files)} files: {', '.join(generated_files)}")


if __name__ == "__main__":
    main()
